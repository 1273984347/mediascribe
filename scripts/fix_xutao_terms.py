def main() -> None:
    files = sorted(OUT.glob("*.md"))
    import os

    state_file = os.environ.get("TERMS_STATE", ".xutao_batch_state.json")
    state = (ROOT / "output" / state_file).read_text(encoding="utf-8")
    p15_files = {Path(json_name).name for json_name in _state_values(state)}
    targets = [f for f in files if f.name in p15_files]
    print(f"目标文件 {len(targets)} 份")

    warn = 0
    for scope, old, new, expected in RULES + RULES_BATCH2 + RULES_BATCH3:
        hits = 0
        for f in targets:
            if scope is not None and scope not in f.name:
                continue
            text = f.read_text(encoding="utf-8")
            if old.startswith("(?"):
                text2, n = re.subn(old, new, text)
            else:
                n = text.count(old)
                text2 = text.replace(old, new)
            if n:
                f.write_text(text2, encoding="utf-8")
                hits += n
        flag = "" if hits == expected else f"  << WARN expected={expected}"
        if hits != expected:
            warn += 1
        print(f"[{hits:2d}/{expected:2d}] {scope or 'GLOBAL'}: {old[:24]} -> {new[:16]}{flag}")
    print(f"\n完成,{warn} 条规则命中数与预期不符,需复查" if warn else "\n完成,全部规则命中符合预期")


def _state_values(state: str) -> list[str]:
    import json

    return list(json.loads(state).values())


if __name__ == "__main__":
    main()
