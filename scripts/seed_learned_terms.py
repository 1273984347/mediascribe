def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true", help="已存在时仍追加/确认")
    args = parser.parse_args()

    store = learned_terms_path()
    if store.exists() and not args.force:
        print(f"术语库已存在: {store}\n如需追加/确认请加 --force")
        return 0

    # 防呆 (10-03 复盘): 文件内重复对会让 test_seed_terms_are_wellformed 挂 CI,
    # 且并行会话共享本文件、各自追加无查重——回填前先在此处硬性拦截
    dupes = [k for k, v in Counter(SAFE_TERMS).items() if v > 1]
    if dupes:
        raise SystemExit(f"SAFE_TERMS 存在重复对, 请先查重再回填: {dupes}")

    db = _load_db()  # 复用 learn 的反序列化(dict -> Correction), 避免 --force 时 dict 崩溃

    # 幂等 upsert (2026-10-02 批四): 已存在的只 confirm, count 不膨胀 —
    # 旧实现每次 --force 走 add() 给旧词 count +1, 重播种 N 次膨胀到 N,
    # 挤掉新回填批次的注入名额(prompt 注入已改为 recency 优先, 见 learn.get_prompt_terms)
    added = 0
    confirmed = 0
    for wrong, right in SAFE_TERMS:
        if not wrong or not right:
            continue
        if db.has(wrong, right):
            db.confirm(wrong, right)
            confirmed += 1
        else:
            db.add(wrong, right)
            db.confirm(wrong, right)  # 人工核定, 直接确认
            added += 1

    _save_db(db)
    print(f"已灌入 {added} 条新术语, 确认 {confirmed} 条已有术语 -> {store}")

    preview = get_prompt_terms()
    print(f"\nprompt 注入预览:\n  {preview[:180]}...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
